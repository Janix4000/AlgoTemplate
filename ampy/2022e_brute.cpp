void solution() {
    ll n;
    cin >> n;
    ll rr = 0;
    for (ll a = 1; a <= n; a++)
    {
        for(ll b = 1; a * (b + 1) <= n; ++b) {
            rr += (n - a) / (b * a);
        }
    }
    cout << rr << endl;
}

int main(void) {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    int qs = 1;
    cin >> qs;

    while (qs--) {
        solution();
    }
    return 0;
}